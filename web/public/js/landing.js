/* Landing page behaviour. Two small things, no dependencies. */

import { vehicleGradientColors } from './pipeline/palette.js';
import { loadSpec, get as specGet } from './spec.js';
import { mountBrand, wireSurfaceLinks } from './chrome.js';
import { initConfigFromSpec } from './config.js';

mountBrand(document.getElementById('brandSlot'), { compact: true });
wireSurfaceLinks();

/* ---------- sticky nav border, only once actually stuck ---------- */
const nav = document.getElementById('topnav');
if (nav) {
  const sentinel = document.createElement('div');
  sentinel.style.cssText = 'position:absolute;top:0;height:1px;width:1px';
  document.body.prepend(sentinel);
  new IntersectionObserver(
    ([e]) => nav.classList.toggle('stuck', !e.isIntersecting),
    { threshold: 0 },
  ).observe(sentinel);
}

/* ---------- before / after ----------
 * A range input does the work: it is draggable, keyboard-operable and
 * screen-reader-labelled for free. It sits invisible over the image and
 * drives a CSS variable; the visible handle is decorative. */
const compare = document.getElementById('compare');
const range = document.getElementById('cmpRange');
if (compare && range) {
  const apply = () => compare.style.setProperty('--split', `${range.value}%`);
  range.addEventListener('input', apply);
  apply();

  // A brief nudge on first view, so it reads as draggable rather than as
  // a static image with a decoration on it. Skipped when the visitor has
  // asked for reduced motion.
  const reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (!reduce) {
    new IntersectionObserver((entries, obs) => {
      if (!entries[0].isIntersecting) return;
      obs.disconnect();
      const from = 50, to = 68, dur = 900;
      const t0 = performance.now();
      const tick = (t) => {
        const p = Math.min(1, (t - t0) / dur);
        // out-and-back, eased
        const e = Math.sin(p * Math.PI);
        range.value = String(from + (to - from) * e);
        apply();
        if (p < 1) requestAnimationFrame(tick);
      };
      setTimeout(() => requestAnimationFrame(tick), 500);
    }, { threshold: 0.6 }).observe(compare);
  }
}

/* ---------- live palette swatches ----------
 * Generated by the same function the app uses, so the claim on this page
 * is demonstrated by the code it describes rather than by hand-picked
 * hex values that could drift away from the truth. */
const swatches = document.getElementById('swatches');
if (swatches) {
  const VEHICLES = [
    ['Azure Gray Metallic Tri-Coat', 'Navy/Aspen Gry'],
    ['Agate Black', 'Ebony'],
    ['Rapid Red Metallic', 'Black Onyx'],
    ['Oxford White', 'Medium Light Slate'],
    ['Carbonized Gray', 'Ebony'],
    ['Atlas Blue', 'Navy Pier'],
  ];
  for (const [ext, int] of VEHICLES) {
    const [a, b] = vehicleGradientColors(ext, int);
    const s = document.createElement('span');
    s.className = 'swatch';
    s.style.background = `linear-gradient(135deg, rgb(${a.join(',')}), rgb(${b.join(',')}))`;
    s.title = ext;
    swatches.appendChild(s);
  }
}

/* ---------- live demo ----------
 * The page runs its own pipeline on demand. Every label and timing below
 * is produced by the run, not written into the markup: the static sort
 * grid above once carried labels I typed by hand, and one of them was
 * wrong (a wheel captioned "front_3q"). Output that describes itself
 * cannot drift away from the truth like that.
 *
 * Nothing loads until the button is pressed, so the 54MB never costs the
 * common visitor anything. */
const liveRun = document.getElementById('liveRun');
if (liveRun) {
  const DEMO = ['demo/lot-1.jpg', 'demo/lot-3.jpg', 'demo/lot-4.jpg', 'demo/lot-2.jpg'];
  const VEHICLE = { ext: 'Azure Gray Metallic Tri-Coat', int: 'Navy/Aspen Gry' };

  const grid = document.getElementById('liveGrid');
  const note = document.getElementById('liveNote');
  const barWrap = document.getElementById('liveBarWrap');
  const bar = document.getElementById('liveBar');
  const out = document.getElementById('liveOut');

  const cells = DEMO.map((src) => {
    const cell = document.createElement('div');
    cell.className = 'live-cell waiting';
    const img = document.createElement('img');
    img.src = src; img.alt = ''; img.loading = 'lazy';
    cell.appendChild(img);
    grid.appendChild(cell);
    return cell;
  });

  const tag = (cell, text, cls) => {
    cell.querySelector('.tag')?.remove();
    const t = document.createElement('span');
    t.className = 'tag';
    t.innerHTML = text;
    cell.appendChild(t);
    if (cls) cell.classList.add(cls);
  };

  liveRun.addEventListener('click', async () => {
    liveRun.disabled = true;
    liveRun.textContent = 'Loading models';
    barWrap.hidden = false;
    const t0 = performance.now();

    try {
      const [{ initRuntime, runtime, loadModel }, cls, mat, comp, io] = await Promise.all([
        import('./pipeline/runtime.js'),
        import('./pipeline/classify.js'),
        import('./pipeline/matte.js'),
        import('./pipeline/compose.js'),
        import('./lib/imageio.js'),
      ]);

      await loadSpec();
      initConfigFromSpec(specGet);
      await initRuntime();
      note.textContent = runtime.isolated
        ? `${runtime.threads} threads, SIMD on`
        : 'single-threaded (no cross-origin isolation)';

      await cls.loadLabels();
      await Promise.all([
        loadModel('scene', (f) => { bar.style.width = `${f * 25}%`; }),
        loadModel('angle'),
        loadModel('matte'),
      ]);
      const loadMs = performance.now() - t0;
      liveRun.textContent = 'Working';

      const t = { scene: [], matte: [], angle: [], compose: [] };
      let hero = null;

      for (let i = 0; i < DEMO.length; i++) {
        const cell = cells[i];
        cell.classList.remove('waiting');
        cell.classList.add('busy');

        const bitmap = await io.decode(DEMO[i]);
        let mark = performance.now();
        const scene = await cls.classifyScene(bitmap);
        t.scene.push(performance.now() - mark);

        tag(cell, `${scene.label} <b>${scene.confidence.toFixed(2)}</b>`);

        // Only exteriors are cut out. This is why a wheel close-up never
        // becomes a hero image: it is classified 'detail' and skipped.
        if (scene.label === 'exterior') {
          mark = performance.now();
          const m = await mat.matte(bitmap);
          t.matte.push(performance.now() - mark);
          const cut = mat.applyMatte(bitmap, m);
          const gate = mat.gateCutout({
            ambiguous: m.ambiguous, coverage: cut.coverage, hasCanvas: !!cut.canvas,
          });

          if (gate.ok) {
            const cutBitmap = await createImageBitmap(await io.canvasToBlob(cut.canvas));
            mark = performance.now();
            const angle = await cls.classifyAngle(cutBitmap);
            t.angle.push(performance.now() - mark);
            if (angle.confidence >= 0.45) {
              tag(cell, `${scene.label} &middot; ${angle.label} <b>${angle.confidence.toFixed(2)}</b>`);
            }
            if (!hero) {
              mark = performance.now();
              hero = comp.composeHero(cut.canvas, {
                seed: DEMO[i], exterior: VEHICLE.ext, interior: VEHICLE.int,
              });
              t.compose.push(performance.now() - mark);
            }
          } else {
            tag(cell, `skipped: ${gate.reason}`, 'skip');
          }
        } else {
          cell.classList.add('skip');
        }

        cell.classList.remove('busy');
        bar.style.width = `${25 + 75 * ((i + 1) / DEMO.length)}%`;
      }

      if (hero) {
        const img = document.getElementById('liveHero');
        img.src = URL.createObjectURL(await io.canvasToBlob(hero, 'image/jpeg', 0.9));
        out.hidden = false;
      }

      const med = (a) => (a.length
        ? Math.round([...a].sort((x, y) => x - y)[Math.floor(a.length / 2)])
        : null);
      const dl = document.getElementById('liveTimings');
      dl.innerHTML = '';
      for (const [label, value] of [
        ['Models', `${(loadMs / 1000).toFixed(1)} s`],
        ['Sort', `${med(t.scene)} ms`],
        ['Cut out', med(t.matte) ? `${med(t.matte)} ms` : 'n/a'],
        ['Angle', med(t.angle) ? `${med(t.angle)} ms` : 'n/a'],
        ['Compose', med(t.compose) ? `${med(t.compose)} ms` : 'n/a'],
      ]) {
        const dt = document.createElement('dt'); dt.textContent = label;
        const dd = document.createElement('dd'); dd.textContent = value;
        dl.append(dt, dd);
      }

      liveRun.textContent = 'Run again';
      liveRun.disabled = false;
      window.LIVEDEMO = { status: 'ok', timings: t };
    } catch (e) {
      note.textContent = `Could not run: ${e.message || e}`;
      liveRun.textContent = 'Run it on this car';
      liveRun.disabled = false;
      window.LIVEDEMO = { status: 'error', error: String(e && e.stack || e) };
    }
  });
}
